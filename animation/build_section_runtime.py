#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Build a track runtime where one continuous TTS passage serves one section.

The manifest stores one TTS entry per section.  This module expands it back
into per-cue runtime entries.  The runtime document carries cue order, audio
source windows and subtitle presentation metadata only; it does not carry a
second playback policy, pause/hold instructions or shared-audio handoff flags.
Cue timing for playback comes from `{track}.audio-slices.json` and the shared
plan generated by `build_cue_timeline.py`.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "animation"))

from section_source import load_track_source  # noqa: E402
from build_tutorial_runtime import load_subtitles, normalize_relative  # noqa: E402


def key_text(text: str) -> str:
    return "".join(ch for ch in str(text or "") if ch.isalnum())


def cue_text(cue: dict) -> str:
    return "".join((b.get("text") or "") for b in cue.get("beats") or [])


def _load_section_subtitles(
    game_dir: Path, cue_entry: dict, duration: float
) -> list[dict]:
    rel = cue_entry.get("subtitle_file")
    if not rel:
        return []
    path = game_dir / normalize_relative(rel, game_dir)
    if path.is_file():
        events = load_subtitles(path, "", duration)
        return [event for event in events if event.get("words")]
    return []


def _word_stream(events: list[dict]) -> list[dict]:
    words: list[dict] = []
    for event in events:
        words.extend(event.get("words") or [])
    words.sort(key=lambda word: (
        float(word.get("start", 0.0) or 0.0),
        float(word.get("end", 0.0) or 0.0),
    ))
    return words


def _match_cue_starts(
    cue_texts: list[str], words: list[dict], duration: float
) -> list[float]:
    """Return cue audio-relative starts.  The first cue always starts at 0."""
    if not cue_texts:
        return []
    if not words:
        weights = [max(1, len(key_text(text))) for text in cue_texts]
        total = sum(weights)
        starts: list[float] = []
        cursor = 0.0
        for weight in weights:
            starts.append(cursor)
            cursor += duration * weight / total
        return starts

    flat_parts: list[str] = []
    char_word: list[int] = []
    for word_index, word in enumerate(words):
        piece = key_text(word.get("word", ""))
        flat_parts.append(piece)
        char_word.extend([word_index] * len(piece))
    flat = "".join(flat_parts)

    starts = []
    cursor = 0
    for index, text in enumerate(cue_texts):
        needle = key_text(text)
        if not needle:
            starts.append(starts[-1] if starts else 0.0)
            continue
        position = flat.find(needle, cursor)
        if position < 0:
            position = flat.find(needle)
        if position < 0:
            starts.append(starts[-1] if starts else 0.0)
            continue
        word_index = char_word[position]
        starts.append(
            0.0 if index == 0
            else float(words[word_index].get("start", 0.0) or 0.0)
        )
        cursor = position + len(needle)
    for index in range(1, len(starts)):
        if starts[index] <= starts[index - 1]:
            starts[index] = starts[index - 1] + 0.001
    return starts


def _slice_subtitles(
    events: list[dict], cue_start: float, cue_end: float
) -> list[dict]:
    result: list[dict] = []
    for event in events:
        event_start = float(event.get("t", 0.0) or 0.0)
        event_end = float(event.get("end", event_start) or event_start)
        if event_end <= cue_start + 1e-6 or event_start >= cue_end - 1e-6:
            continue
        local_start = max(event_start, cue_start) - cue_start
        local_end = min(event_end, cue_end) - cue_start
        words: list[dict] = []
        for word in event.get("words") or []:
            word_start = float(word.get("start", 0.0) or 0.0)
            word_end = float(word.get("end", word_start) or word_start)
            if word_end <= cue_start + 1e-6 or word_start >= cue_end - 1e-6:
                continue
            words.append({
                "word": word.get("word", ""),
                "start": round(max(word_start, cue_start) - cue_start, 3),
                "end": round(max(word_end, cue_start) - cue_start, 3),
                "confidence": float(word.get("confidence", 0.0) or 0.0),
            })
        result.append({
            "t": round(local_start, 3),
            "end": round(max(local_end, local_start), 3),
            "text": event.get("text", ""),
            "words": words,
        })
    return result


def _cue_local_id(cue: dict) -> str:
    local_id = str(cue.get("local_id") or "").strip()
    if local_id:
        return local_id
    return str(cue.get("id") or "").strip().rsplit("/", 1)[-1]


def _pseudo_words(text: str, duration: float) -> list[dict]:
    chars = [ch for ch in str(text or "") if ch.isalnum()]
    if not chars:
        return []
    step = max(0.08, float(duration) / max(1, len(chars)))
    return [{
        "word": ch,
        "start": round(index * step, 3),
        "end": round((index + 1) * step, 3),
        "confidence": 0.0,
    } for index, ch in enumerate(chars)]


def build_section_runtime(
    game: str,
    track: str,
    *,
    force: bool = False,
    manifest: dict | None = None,
) -> Path:
    game_dir = ROOT / "content" / "games" / game
    manifest_path = game_dir / "media" / "tts" / track / "tts_manifest.json"
    output_path = game_dir / "tutorial" / f"{track}.runtime.json"
    if manifest is None:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    source = load_track_source(game, track)

    manifest_by = {
        str(cue.get("id")): cue
        for cue in manifest.get("cues") or []
        if isinstance(cue, dict) and cue.get("id")
    }
    gap = float(manifest.get("gap_seconds", 0.0) or 0.0)

    source_cues_by_section: dict[str, list[dict]] = {}
    for cue in source.script_doc.get("cues") or []:
        if not isinstance(cue, dict) or not cue.get("id"):
            continue
        source_cues_by_section.setdefault(
            str(cue.get("section") or ""), []).append(cue)

    sections_out: list[dict[str, Any]] = []
    cues_out: list[dict[str, Any]] = []
    section_cursor = 0.0
    global_index = 0
    for section in source.sections:
        entry = manifest_by.get(section.id)
        if entry is None:
            raise SystemExit(f"missing section TTS manifest entry: {section.id}")
        source_cues = source_cues_by_section.get(section.id) or []
        if not source_cues:
            raise SystemExit(f"section {section.id}: no script cues")
        audio_rel = normalize_relative(str(entry.get("file") or ""), game_dir)
        audio_path = game_dir / audio_rel
        if not audio_path.exists():
            raise SystemExit(f"missing section audio: {audio_path}")
        duration = float(entry.get("duration", 0.0) or 0.0)
        if duration <= 0.0:
            raise SystemExit(f"section {section.id}: invalid TTS duration")
        events = _load_section_subtitles(game_dir, entry, duration)
        cue_texts = [cue_text(cue) for cue in source_cues]
        starts = _match_cue_starts(cue_texts, _word_stream(events), duration)
        section_start = section_cursor
        cue_cursor = section_start

        section_meta = {
            "id": section.id,
            "title": str(section.meta.get("title") or ""),
            "group_path": list(section.meta.get("group_path") or []),
            "order": section.order,
            "asset": str(entry.get("asset") or section.id),
            "audio": audio_rel,
            "start": round(section_start, 3),
            "cue_ids": [str(cue.get("id")) for cue in source_cues],
        }

        for index, (source_cue, cue_start) in enumerate(zip(source_cues, starts)):
            local_end = starts[index + 1] if index + 1 < len(starts) else duration
            cue_end = max(cue_start + 0.001, local_end)
            cue_duration = max(0.001, cue_end - cue_start)
            text = cue_texts[index]
            subtitles = _slice_subtitles(events, cue_start, cue_end)
            if not subtitles:
                subtitles = [{
                    "t": 0.0,
                    "end": round(cue_duration, 3),
                    "text": text,
                    "words": _pseudo_words(text, cue_duration),
                }]
            else:
                subtitles[0]["t"] = 0.0
                last = max(subtitles, key=lambda sub: float(sub.get("end", 0.0) or 0.0))
                last["end"] = round(cue_duration, 3)
                for subtitle in subtitles:
                    subtitle["t"] = max(0.0, float(subtitle.get("t", 0.0) or 0.0))
                    subtitle["end"] = min(
                        round(cue_duration, 3),
                        max(float(subtitle.get("end", 0.0) or 0.0),
                            float(subtitle.get("t", 0.0) or 0.0)),
                    )

            group = source_cue.get("group") or section.meta.get("title") or section.id
            group_path = (
                source_cue.get("group_path")
                or section.meta.get("group_path")
                or [group]
            )
            cues_out.append({
                "id": str(source_cue.get("id")),
                "section": section.id,
                "local_id": str(
                    source_cue.get("local_id") or _cue_local_id(source_cue)),
                "section_index": section.order,
                "local_index": index,
                "cue_index": global_index,
                "group": group,
                "group_path": list(group_path),
                "text": text,
                "audio": audio_rel,
                "audio_start": round(cue_start, 3),
                "duration": round(cue_duration, 3),
                "start": round(cue_cursor, 3),
                "refs": list(source_cue.get("refs") or []),
                "subtitles": subtitles,
                "animation": None,
            })
            cue_cursor += cue_duration
            global_index += 1

        section_meta["duration"] = round(cue_cursor - section_start, 3)
        sections_out.append(section_meta)
        section_cursor = cue_cursor + gap

    runtime = {
        "schema_version": 3,
        "game_id": game,
        "track": track,
        "title": source.script_doc.get("title") or f"{game} {track}",
        "voice": manifest.get("voice", ""),
        "format": manifest.get("format", "mp3"),
        "sample_rate": manifest.get("sample_rate", 24000),
        "generator": "animation/build_section_runtime.py",
        "units": "section",
        "sections": sections_out,
        "cues": cues_out,
    }
    if output_path.exists() and not force:
        raise SystemExit(f"output exists, use --force: {output_path}")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        json.dumps(runtime, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8")
    print(f"[runtime] {output_path}")
    print(f"sections: {len(sections_out)}  cues: {len(cues_out)}")
    print(f"duration: {section_cursor:.2f}s")
    return output_path
